"""Download Glazy open data and convert to compact JSON for the community recipes feature.

Run this once to populate data/glazy_bulk/glazy_recipes.json.
Data source: https://github.com/derekphilipau/glazy-data (CC BY-NC-SA 4.0)
"""

import datetime
import gzip
import json
import shutil
import urllib.request
from pathlib import Path

DATA_DIR = Path(__file__).parent.parent / "data" / "glazy_bulk"
# Upstream publishes dated snapshots rather than a rolling "latest", so
# this pin has to be bumped by hand to pick up a newer one - re-running
# as-is re-fetches the same February file.
SNAPSHOT_DATE = "2026-02-27"
YAML_URL = "https://raw.githubusercontent.com/derekphilipau/glazy-data/master/glazy-20260227.yaml.gz"
OUTPUT_FILE = DATA_DIR / "glazy_recipes.json"
METADATA_FILE = DATA_DIR / ".metadata.json"


def download_and_convert():
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    if OUTPUT_FILE.exists():
        print(f"Data already exists at {OUTPUT_FILE} ({OUTPUT_FILE.stat().st_size / 1024 / 1024:.1f} MB)")
        resp = input("Re-download? [y/N] ").strip().lower()
        if resp != "y":
            return

    gz_path = DATA_DIR / "glazy-20260227.yaml.gz"

    # Download
    print(f"Downloading {YAML_URL}...")
    urllib.request.urlretrieve(YAML_URL, gz_path)
    print(f"Downloaded {gz_path.stat().st_size / 1024 / 1024:.1f} MB")

    # Decompress
    yaml_path = DATA_DIR / "glazy-20260227.yaml"
    print("Decompressing...")
    with gzip.open(gz_path, "rb") as f_in, open(yaml_path, "wb") as f_out:
        shutil.copyfileobj(f_in, f_out)

    # Parse YAML
    print("Parsing YAML (this takes a moment)...")
    import yaml

    with open(yaml_path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)

    print(f"Loaded {len(data)} entries")

    # Extract glaze recipes
    glazes = []
    for entry in data:
        subtype = entry.get("Subtype", "")
        if not subtype.startswith("Glaze"):
            continue
        ings = entry.get("Ingredients", [])
        if not ings:
            continue
        analysis = entry.get("Percent Analysis", {})
        if not analysis:
            continue

        atm = entry.get("Atmospheres", [])
        if isinstance(atm, str):
            atm = [atm]

        glazes.append(
            {
                "id": entry.get("ID"),
                "name": entry.get("Name", ""),
                "cone": entry.get("Cone", ""),
                "surface": entry.get("Surface", ""),
                "atmospheres": atm or [],
                "subtype": subtype,
                "description": (entry.get("Description") or "")[:200],
                "ingredients": [
                    {"name": i["Name"], "pct": i["Percentage"], "add": i.get("Additional", False)}
                    for i in ings
                    if i.get("Name") and i.get("Percentage")
                ],
                "analysis": {k: round(v, 2) for k, v in analysis.items() if v and v > 0},
            }
        )

    print(f"Extracted {len(glazes)} glaze recipes")

    # Save compact JSON
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(glazes, f, separators=(",", ":"))

    size_mb = OUTPUT_FILE.stat().st_size / 1024 / 1024
    print(f"Saved to {OUTPUT_FILE} ({size_mb:.1f} MB)")

    write_metadata(len(glazes))

    # Clean up
    yaml_path.unlink(missing_ok=True)
    gz_path.unlink(missing_ok=True)
    print("Cleaned up temporary files. Done!")


def write_metadata(recipe_count: int) -> None:
    """Refresh the attribution file the app reads.

    This data is CC BY-NC-SA 4.0, so crediting the source is a licence
    condition rather than a nicety, and the credit has to survive a
    re-download. Everything else in data/glazy_bulk/ is gitignored; this
    one file is deliberately not, so the attribution ships with the repo
    and reaches the deployed app.
    """
    metadata = {
        "source": "glazy-data",
        "title": "Glazy open data",
        "creator": "Glazy.org, compiled by Derek Philip Au",
        "source_url": "https://github.com/derekphilipau/glazy-data",
        "project_url": "https://glazy.org",
        "license": "CC BY-NC-SA 4.0",
        "license_url": "https://creativecommons.org/licenses/by-nc-sa/4.0/",
        "attribution": (
            "Community recipe data from Glazy.org (compiled by Derek Philip Au), "
            "licensed CC BY-NC-SA 4.0."
        ),
        "snapshot": Path(YAML_URL).name,
        "snapshot_date": SNAPSHOT_DATE,
        "last_updated": datetime.date.today().isoformat(),
        "recipe_count": recipe_count,
        "_note": (
            "Regenerated by scripts/download_glazy_data.py. Un-ignored in "
            ".gitignore so the licence credit travels with the repo. Note the "
            "NonCommercial term."
        ),
    }
    with open(METADATA_FILE, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)
        f.write("\n")
    print(f"Wrote attribution metadata to {METADATA_FILE}")


if __name__ == "__main__":
    download_and_convert()
